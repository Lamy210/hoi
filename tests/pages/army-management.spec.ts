import { expect, test } from '@playwright/test';
test('通常UIで軍団・軍集団を作成し師団を編入、集計・所在地・補給を確認する',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  await page.getByTestId('roster-mode-list').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  const roster=page.getByTestId('unit-roster');
  const ids=await roster.locator('[data-unit-id]').evaluateAll(rows=>rows.map(r=>r.getAttribute('data-unit-id')!));
  expect(ids.length).toBeGreaterThanOrEqual(2);
  await page.getByTestId('toggle-army-editor').click();
  await page.getByTestId('army-name').fill('第1軍団');
  await page.getByTestId('create-army').click(); await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('army-select-1')).toContainText('第1軍団');
  await page.getByTestId('army-name').fill('第1軍集団');
  await page.getByTestId('create-army-group').click(); await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('group-select-1')).toContainText('第1軍集団');
  await page.getByTestId('unit-roster-'+ids[0]).click();
  await page.getByTestId('unit-check-'+ids[1]).check();
  await page.getByTestId('army-target').selectOption('1');
  await page.getByTestId('assign-army').click(); await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('army-select-1')).toContainText('2/24');
  await page.getByTestId('group-target').selectOption('1');
  await page.getByTestId('assign-army-group').click(); await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('group-select-1')).toContainText('1/5');
  await page.getByTestId('group-select-1').click();
  await expect(page.getByTestId('selected-unit-count')).toContainText('2');
  const combatPanel=page.getByTestId('combat-frontage-inspector');
  await expect(combatPanel).toBeVisible();
  await expect(combatPanel).toContainText('戦闘幅・前線参加状況');
  await expect(page.getByTestId('combat-frontage-unit-'+ids[0])).toContainText('幅');
  await expect(page.getByTestId('combat-frontage-unit-'+ids[1])).toBeVisible();
  // Peace-time summaries are estimates: do not mislabel them as actual combat.
  await expect(combatPanel).toContainText('事前見積り');
  // Set a shared combat-only priority for both selected divisions.
  const frontlineSelect=page.getByTestId('combat-frontline-priority-select');
  await expect(frontlineSelect).toHaveValue('5');
  await frontlineSelect.selectOption('9');
  await page.getByTestId('apply-pending').click();
  await expect(frontlineSelect).toHaveValue('9');
  await expect(page.getByTestId('combat-frontage-unit-'+ids[0])).toContainText('優先度 9');
  await expect(page.getByTestId('combat-frontage-unit-'+ids[1])).toContainText('優先度 9');
  await expect(page.getByTestId('army-summary')).toContainText('平均補給効率');
  await expect(page.getByTestId('move-selected')).toBeEnabled();
  await page.getByTestId('roster-filter').selectOption('selected');
  await expect(roster.locator('[data-unit-id]')).toHaveCount(2);
  await page.getByTestId('unit-roster-'+ids[0]).click();
  await expect(page.getByTestId('context-unit-resources-'+ids[0])).toContainText('歩兵装備');
  await expect(page.getByTestId('context-unit-resources-'+ids[0])).toContainText('容量係数');
  await expect(page.getByTestId('unit-location')).toBeVisible();
  await page.getByTestId('roster-query').fill('not-a-real-province-id');
  await expect(roster.locator('[data-unit-id]')).toHaveCount(0);
  await page.getByTestId('roster-query').fill('');
  await page.getByTestId('army-supply-map').click();
});
