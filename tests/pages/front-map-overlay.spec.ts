import {expect,test} from '@playwright/test';
test.use({deviceScaleFactor:2});
test('戦線の表示・所属師団選択・拡大・非表示',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-KOR').click();
  await page.getByTestId('btn-start').click();
  await page.getByTestId('roster-mode-list').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  await page.getByTestId('btn-province-search').click();
  await page.getByTestId('province-search').fill('KP-07');
  await page.getByTestId('search-result-KP-07').click();
  await page.getByTestId('btn-declare-war').click();
  await page.getByTestId('apply-pending').click();
  const unit=page.getByTestId('unit-roster').locator('[data-location="KR-41"]').first();
  await unit.click();
  await page.getByTestId('open-selected-fronts').click();
  await page.getByTestId('btn-create-front').click();
  await page.getByTestId('apply-pending').click();
  const front=page.getByTestId('fronts-modal').locator('button[data-testid^="front-assign-"]').first();
  const id=(await front.getAttribute('data-testid'))!.replace('front-assign-','');
  await front.click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('front-stance-attack').click();await page.getByTestId('apply-pending').click();
  const select=page.getByTestId('front-target-'+id);
  const value=await select.locator('option').evaluateAll(o=>(o.find(x=>x.textContent?.includes('(KP-07)')) as HTMLOptionElement|undefined)?.value);
  if(!value)throw new Error('Missing target');
  await select.selectOption(value);await page.getByTestId('apply-pending').click();
  await page.getByTestId('close-fronts').click();
  const overlay=page.getByTestId('map-front-'+id);
  await expect(overlay).toHaveAttribute('data-highlighted','true');
  await expect(overlay.locator('.front-target')).toHaveCount(1);
  await page.getByTestId('front-overview').locator('summary').click();
  await page.getByTestId('focus-front-'+id).click();
  await page.getByTestId('map-zoom-in').click();
  await expect(overlay.locator('.front-province').first()).toBeVisible();
  await page.getByTestId('select-front-units-'+id).click();
  await expect(page.getByTestId('front-visibility')).toHaveValue('selected');
  await expect(overlay).toHaveAttribute('data-highlighted','true');
  await page.getByTestId('front-visibility').selectOption('off');
  await expect(overlay).toHaveCount(0);
  await page.getByTestId('front-visibility').selectOption('all');
  await expect(overlay).toBeAttached();
});
