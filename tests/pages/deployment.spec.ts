import { test, expect } from '@playwright/test';

test('公開用ビルドが /hoi/ で起動して地図と時間進行を提供する', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const packFailures: string[] = [];
  page.on('response', (response) => {
    if (response.url().includes('/packs/') && !response.ok()) packFailures.push(response.url());
  });
  await page.goto('/hoi/?e2e=1');
  await expect(page.getByTestId('btn-new-game')).toBeVisible();
  expect(await page.evaluate(() => '__orbis' in window)).toBe(false);
  await page.getByTestId('btn-new-game').click();
  await expect(page.getByTestId('scenario-card')).toBeVisible();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  const date = page.getByTestId('date');
  await expect(date).toContainText('2026-01-01');
  await expect(page.getByTestId('map').locator('canvas').first()).toBeVisible({ timeout: 20000 });
  await page.getByTestId('speed-4').click();
  await expect(date).not.toContainText('2026-01-01', { timeout: 15000 });
  await page.getByTestId('speed-0').click();
  expect(packFailures).toEqual([]);
  expect(errors).toEqual([]);
});

test('公開版でズーム・ドラッグ・研究・戦争画面を通常操作できる', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  const map = page.getByTestId('map');
  const canvas = map.locator('canvas').first();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({ timeout: 30000 });
  const image = await canvas.screenshot();
  await page.getByTestId('map-zoom-in').click();
  await expect(canvas).toHaveAttribute('data-zoom', '1.25');
  expect((await canvas.screenshot()).equals(image)).toBe(false);
  const rect = await canvas.boundingBox();
  if (!rect) throw new Error('map missing');
  await page.mouse.move(rect.x + rect.width * 0.6, rect.y + rect.height * 0.4);
  await page.mouse.wheel(0, -120);
  await expect(canvas).toHaveAttribute('data-lod', '1');
  const beforePan = await canvas.getAttribute('data-camera-x');
  const beforePanImage = await canvas.screenshot();
  await page.mouse.move(rect.x + rect.width * 0.6, rect.y + rect.height * 0.4);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * 0.6 + 90, rect.y + rect.height * 0.4 + 40, { steps: 5 });
  await page.mouse.up();
  await expect(canvas).not.toHaveAttribute('data-camera-x', beforePan!);
  expect((await canvas.screenshot()).equals(beforePanImage)).toBe(false);
  await expect(page.getByTestId('province-panel')).toHaveCount(0);
  await page.getByTestId('map-reset').click();
  await expect(canvas).toHaveAttribute('data-zoom', '1');
  await page.getByTestId('btn-research').click();
  const research = page.getByTestId('research-tab');
  await expect(research).toBeVisible();
  const start = research.getByTestId('research-industry-basic');
  await expect(start).toBeEnabled();
  await start.click();
  const pending = page.getByTestId('budget-modal').getByTestId('pending-orders');
  await expect(pending).toBeVisible();
  await pending.getByTestId('apply-pending').click();
  await expect(start).toHaveCount(0);
  await expect(pending).toHaveCount(0);
  await expect(page.getByTestId('date')).toContainText('2026-01-02');
  await page.keyboard.press('Escape');
  await page.getByTestId('btn-wars').click();
  await expect(page.getByTestId('dip-peace')).toBeVisible();
  expect(errors).toEqual([]);
});
