import {test,expect} from '@playwright/test';

test('軍のチェック複数選択から軍集団へ一括編入・解除し、師団の即時移籍とShift範囲選択を行う',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  await page.getByTestId('toggle-army-editor').click();
  await page.getByTestId('army-name').fill('第一軍');
  await page.getByTestId('create-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-name').fill('第二軍');
  await page.getByTestId('create-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-name').fill('北方軍集団');
  await page.getByTestId('create-army-group').click();await page.getByTestId('apply-pending').click();
  const form=page.getByTestId('formation-assignment-panel');
  await expect(form).toBeVisible();
  await page.getByTestId('assignment-select-unassigned-armies').click();
  await expect(page.getByTestId('assignment-selected-armies')).toHaveText('2');
  await page.getByTestId('assignment-group-target').selectOption('1');
  await expect(page.getByTestId('assignment-group-capacity')).toContainText('0 → 2/5');
  await page.getByTestId('assignment-assign-armies').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('group-select-1')).toContainText('2/5');
  await expect(page.getByTestId('assignment-assign-armies')).toBeDisabled();
  await expect(page.getByTestId('assignment-group-reason')).toContainText('すでに');
  await page.getByTestId('assignment-unassign-armies').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('group-select-1')).toContainText('0/5');
  await page.getByTestId('assignment-assign-armies').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('group-select-1')).toContainText('2/5');

  const tree=page.getByTestId('order-of-battle');
  const divisionButtons=tree.locator('[data-testid^="oob-unit-"]');
  await expect(divisionButtons.nth(1)).toBeVisible();
  const first=divisionButtons.nth(0),second=divisionButtons.nth(1);
  const ids=[(await first.getAttribute('data-testid'))!.replace('oob-unit-',''),
    (await second.getAttribute('data-testid'))!.replace('oob-unit-','')];
  await first.click();
  await second.click({modifiers:['Shift']});
  await expect(page.getByTestId('oob-selected-count')).toContainText('2/256');
  await page.getByTestId('assignment-division-target').selectOption('2');
  await expect(page.getByTestId('assignment-division-capacity')).toContainText('0 → 2/24');
  await page.getByTestId('assignment-assign-divisions').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('army-select-2')).toContainText('2/24');
  await expect(page.getByTestId('oob-army-2')).toContainText('第二軍');
  await page.getByTestId('assignment-division-target').selectOption('1');
  await page.getByTestId('assignment-assign-divisions').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('army-select-1')).toContainText('2/24');
  await expect(page.getByTestId('army-select-2')).toContainText('0/24');
  await page.getByTestId('oob-search').fill(ids[0]);
  await expect(page.getByTestId('oob-visible-count')).toContainText('1 /');
  await page.getByTestId('oob-search').fill('');
  await page.getByTestId('oob-clear-selection').click();
  await expect(page.getByTestId('oob-selected-count')).toContainText('0/256');
  await page.getByTestId('oob-select-visible').click();
  await expect(page.getByTestId('assignment-selected-divisions')).not.toHaveText('0');
  await page.getByTestId('oob-clear-selection').click();
  await expect(page.getByTestId('assignment-assign-divisions')).toBeDisabled();
});
