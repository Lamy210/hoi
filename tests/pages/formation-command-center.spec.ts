import {expect,test} from '@playwright/test';

test('軍集団指揮画面で2師団を集計し自動作戦の保留と再開を一括指示できる',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  const center=page.getByTestId('formation-command-center');
  await expect(center).toBeVisible();
  await expect(page.getByTestId('formation-focused-name')).toHaveCount(0);
  await page.getByTestId('roster-mode-list').click();
  const ids=await page.getByTestId('unit-roster').locator('[data-unit-id]')
    .evaluateAll(rows=>rows.map(r=>r.getAttribute('data-unit-id')!));
  expect(ids.length).toBeGreaterThanOrEqual(2);
  await page.getByTestId('toggle-army-editor').click();
  await page.getByTestId('army-name').fill('第1軍');
  await page.getByTestId('create-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-name').fill('北方軍集団');
  await page.getByTestId('create-army-group').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('unit-roster-'+ids[0]).click();
  await page.getByTestId('unit-check-'+ids[1]).check();
  await page.getByTestId('army-target').selectOption('1');
  await page.getByTestId('assign-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('group-target').selectOption('1');
  await page.getByTestId('assign-army-group').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('group-select-1').click();
  await expect(page.getByTestId('formation-focused-name')).toContainText('北方軍集団');
  await expect(page.getByTestId('formation-count')).toHaveText('2');
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await expect(page.getByTestId('formation-group-armies')).toBeVisible();
  await expect(page.getByTestId('formation-group-front-1')).toBeVisible();
  await expect(page.getByTestId('formation-group-front-assign')).toBeDisabled();
  await expect(page.getByTestId('formation-group-front-deploy')).toBeDisabled();
  await expect(page.getByTestId('formation-army-readiness-1')).toContainText('未配属');
  await expect(page.getByTestId('formation-army-readiness-1')).toContainText('2');
  await page.getByTestId('formation-target-army-1').click();
  await expect(page.getByTestId('formation-target-scope')).toHaveValue('selected');
  await expect(page.getByTestId('formation-toggle-army-1')).toHaveAttribute('aria-pressed','true');
  await page.getByTestId('formation-toggle-army-1').click();
  await expect(page.getByTestId('formation-target-count')).toContainText('0 / 2');
  await page.getByTestId('formation-toggle-army-1').click();
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await expect(page.getByTestId('formation-command-preview')).toContainText('保留');
  await page.getByTestId('formation-target-scope').selectOption('selected');
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await page.getByTestId('formation-target-scope').selectOption('withoutFront');
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await page.getByTestId('formation-target-scope').selectOption('all');
  await expect(page.getByTestId('formation-operational-summary')).toContainText('平均補給');
  await expect(page.getByTestId('formation-equipment-deficit')).toContainText('歩兵装備');
  await expect(page.getByTestId('formation-front-select')).toBeEnabled();
  await expect(page.getByTestId('formation-assign-front')).toBeDisabled();
  await expect(page.getByTestId('formation-deployment-mode')).toBeVisible();
  await expect(page.getByTestId('formation-deploy-front')).toBeDisabled();
  await expect(page.getByTestId('formation-no-fronts')).toBeVisible();
  await page.getByTestId('formation-manual-hold').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-resume')).toBeEnabled();
  await expect(page.getByTestId('formation-focused-commander')).toContainText('未配置');
  await page.getByTestId('formation-resume').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-manual-hold')).toBeEnabled();
  await expect(page.getByTestId('formation-resume')).toBeDisabled();
  await page.getByTestId('formation-select-all').click();
  await expect(page.getByTestId('selected-unit-count')).toContainText('2');
  await page.getByTestId('army-select-1').click();
  await expect(page.getByTestId('formation-focused-name')).toContainText('第1軍');
  await expect(page.getByTestId('formation-count')).toHaveText('2');
  await page.getByTestId('roster-mode-tree').click();
  await page.getByTestId('oob-select-group-1').click();
  await expect(page.getByTestId('formation-focused-name')).toContainText('北方軍集団');
});

test('戦線割当による手動固定の解除確認を必須にし、対象変更で確認を失効させる',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-KOR').click();
  await page.getByTestId('btn-start').click();
  await page.getByTestId('roster-mode-list').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  await page.getByTestId('btn-province-search').click();
  await page.getByTestId('province-search').fill('KP-07');
  await page.getByTestId('search-result-KP-07').click();
  await page.getByTestId('btn-declare-war').click();
  await page.getByTestId('apply-pending').click();
  const ids=await page.getByTestId('unit-roster').locator('[data-unit-id]')
    .evaluateAll(rows=>rows.map(r=>r.getAttribute('data-unit-id')!));
  expect(ids.length).toBeGreaterThanOrEqual(2);
  await page.getByTestId('unit-roster-'+ids[0]).click();
  await page.getByTestId('unit-check-'+ids[1]).check();
  await page.getByTestId('open-selected-fronts').click();
  await page.getByTestId('btn-create-front').click();
  await page.getByTestId('apply-pending').click();
  const frontButton=page.getByTestId('fronts-modal').locator('button[data-testid^="front-pause-"]').first();
  const frontTestId=await frontButton.getAttribute('data-testid');
  if(!frontTestId)throw new Error('front missing');
  const frontId=frontTestId.replace('front-pause-','');
  await page.getByTestId('close-fronts').click();
  await page.getByTestId('toggle-army-editor').click();
  await page.getByTestId('army-name').fill('テスト軍');
  await page.getByTestId('create-army').click();
  await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-target').selectOption('1');
  await page.getByTestId('assign-army').click();
  await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-select-1').click();
  await expect(page.getByTestId('formation-count')).toHaveText('2');
  await page.getByTestId('formation-manual-hold').click();
  await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-manual-hold-count')).toHaveText('2');
  await page.getByTestId('formation-front-select').selectOption(frontId);
  await expect(page.getByTestId('formation-deploy-front')).toBeDisabled();
  await expect(page.getByTestId('formation-deployment-hint')).toContainText('手動固定中');
  await expect(page.getByTestId('formation-release-warning')).toContainText('2師団');
  await expect(page.getByTestId('formation-assign-front')).toBeDisabled();
  await page.getByTestId('formation-confirm-release').check();
  await expect(page.getByTestId('formation-assign-front')).toBeEnabled();
  await page.getByTestId('formation-target-scope').selectOption('withoutFront');
  await expect(page.getByTestId('formation-confirm-release')).not.toBeChecked();
  await expect(page.getByTestId('formation-assign-front')).toBeDisabled();
  await page.getByTestId('formation-confirm-release').check();
  await page.getByTestId('formation-assign-front').click();
  await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-front-assigned')).toHaveText('2');
  await expect(page.getByTestId('formation-manual-hold-count')).toHaveText('0');
  // Previous assertion used "withoutFront"; the assigned units are now excluded by that filter.
  await page.getByTestId('formation-target-scope').selectOption('all');
  await expect(page.getByTestId('formation-target-count')).toContainText('2 / 2');
  await page.getByTestId('formation-deployment-mode').selectOption('even');
  await expect(page.getByTestId('formation-deploy-front')).toBeEnabled();
  await page.getByTestId('formation-deploy-front').click();
  await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-front-assigned')).toHaveText('2');
});
