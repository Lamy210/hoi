import {expect,test} from '@playwright/test';

test('軍集団指揮画面で2師団を集計し自動作戦の保留と再開を一括指示できる',async({page})=>{
  await page.goto('/hoi/');
  await page.getByTestId('btn-new-game').click();
  await page.getByTestId('btn-to-country').click();
  await page.getByTestId('country-JPN').click();
  await page.getByTestId('btn-start').click();
  await expect(page.getByTestId('map-zoom-in')).toBeEnabled({timeout:30000});
  const center=page.getByTestId('formation-command-center');
  await expect(center).toBeVisible();
  await expect(page.getByTestId('formation-focused-name')).toHaveCount(0);
  await page.getByTestId('roster-mode-list').click();
  const ids=await page.getByTestId('unit-roster').locator('[data-unit-id]')
    .evaluateAll(rows=>rows.map(r=>r.getAttribute('data-unit-id')!));
  expect(ids.length).toBeGreaterThanOrEqual(2);
  await page.getByTestId('toggle-army-editor').click();
  await page.getByTestId('army-name').fill('第1軍');
  await page.getByTestId('create-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('army-name').fill('北方軍集団');
  await page.getByTestId('create-army-group').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('unit-roster-'+ids[0]).click();
  await page.getByTestId('unit-check-'+ids[1]).check();
  await page.getByTestId('army-target').selectOption('1');
  await page.getByTestId('assign-army').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('group-target').selectOption('1');
  await page.getByTestId('assign-army-group').click();await page.getByTestId('apply-pending').click();
  await page.getByTestId('group-select-1').click();
  await expect(page.getByTestId('formation-focused-name')).toContainText('北方軍集団');
  await expect(page.getByTestId('formation-count')).toHaveText('2');
  await expect(page.getByTestId('formation-operational-summary')).toContainText('平均補給');
  await expect(page.getByTestId('formation-equipment-deficit')).toContainText('歩兵装備');
  await expect(page.getByTestId('formation-front-select')).toBeEnabled();
  await expect(page.getByTestId('formation-assign-front')).toBeDisabled();
  await expect(page.getByTestId('formation-no-fronts')).toBeVisible();
  await page.getByTestId('formation-manual-hold').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-resume')).toBeEnabled();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-manual-hold')).toBeDisabled();
  await expect(page.getByTestId('formation-focused-commander')).toContainText('未配置');
  await page.getByTestId('formation-resume').click();await page.getByTestId('apply-pending').click();
  await expect(page.getByTestId('formation-manual-hold')).toBeEnabled();
  await expect(page.getByTestId('formation-resume')).toBeDisabled();
  await page.getByTestId('formation-select-all').click();
  await expect(page.getByTestId('selected-unit-count')).toContainText('2');
  await page.getByTestId('army-select-1').click();
  await expect(page.getByTestId('formation-focused-name')).toContainText('第1軍');
  await expect(page.getByTestId('formation-count')).toHaveText('2');
});
