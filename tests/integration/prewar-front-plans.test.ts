import {describe,expect,it} from 'vitest';
import {createTestEngine} from '../helpers';
import {applyCommands} from '../../src/engine/core/command';
import {startWar} from '../../src/engine/military/war';
import {runFront} from '../../src/engine/systems/fronts';
import {frontView} from '../../src/ui/maprender/frontView';
import {hashWorld} from '../../src/engine/core/hash';

describe('prewar frontline planning and offensive activation',()=>{
  it('drafts a front, assigns divisions and saves objectives without deploying orders before war',async()=>{
    const e=await createTestEngine(1,12,'KOR'),w=e.world;
    const c=w.playerCountry,enemy=w.countries.id.indexOf('PRK');
    const from=w.prov.id.indexOf('KR-41'),to=w.prov.id.indexOf('KP-07');
    const own=w.units.filter(u=>u.owner===c&&!u.destroyed);
    let seq=0;
    const issue=(type:string,p:Record<string,unknown>)=>applyCommands(w,[{issuer:'player',seq:++seq,type,p}])[0];
    expect(issue('createFront',{enemy}).reason).toBe('notAtWar');
    expect(w.fronts).toHaveLength(0);
    expect(issue('createFront',{enemy,provinces:[from]}).ok).toBe(true);
    const front=w.fronts[0];
    expect(front.paused).toBe(true);
    expect(front.stance).toBe('hold');
    expect(issue('setManualHold',{units:[own[0].id],hold:true}).ok).toBe(true);
    expect(issue('assignToFront',{frontId:front.id,units:own.slice(0,3).map(u=>u.id)}).ok).toBe(true);
    expect(own[0].manualHold).toBe(true);
    expect(issue('setFrontStance',{frontId:front.id,stance:'attack',targets:[to]}).ok).toBe(true);
    expect(front.paused).toBe(true);
    expect(issue('setFrontPaused',{frontId:front.id,paused:false}).reason).toBe('notAtWar');
    const before=own.map(u=>u.path.slice());
    runFront(w,front,()=>0.5);
    expect(own.map(u=>u.path)).toEqual(before);
    expect(w.runtime.commandsSinceLastTick.every(c=>c.type!=='frontMove')).toBe(true);
    const view=frontView(e.getUiSnapshot(0),[own[0].id],'selected')[0];
    expect(view?.planned).toBe(true);
    expect(view?.targets).toEqual([to]);
    expect(view?.arrows).toEqual([]);
    const stateHash=hashWorld(w),data=e.serialize();
    expect(e.loadFrom(data).ok).toBe(true);
    expect(hashWorld(e.world)).toBe(stateHash);
    expect(e.world.fronts[0].targets).toEqual([to]);
    expect(e.world.fronts[0].paused).toBe(true);
    expect(e.world.units.find(u=>u.id===own[0].id)?.manualHold).toBe(true);
    startWar(e.world,c,enemy,false);
    const front2=e.world.fronts[0],beforeResume=e.world.units.map(u=>u.path.slice());
    runFront(e.world,front2,()=>0.5);
    expect(e.world.units.map(u=>u.path)).toEqual(beforeResume);
    const resume=applyCommands(e.world,[{issuer:'player',seq:++seq,type:'setFrontPaused',p:{frontId:front2.id,paused:false}}])[0];
    expect(resume.ok).toBe(true);
    expect(front2.paused).toBe(false);
  });
  it('rejects prewar invalid province, foreign assignment and stale automatic movement',async()=>{
    const e=await createTestEngine(1,13,'KOR'),w=e.world,c=w.playerCountry;
    const enemy=w.countries.id.indexOf('PRK'),to=w.prov.id.indexOf('KP-07'),from=w.prov.id.indexOf('KR-41');
    let seq=0;
    const issue=(type:string,p:Record<string,unknown>)=>applyCommands(w,[{issuer:'player',seq:++seq,type,p}])[0];
    expect(issue('createFront',{enemy,provinces:[to]}).reason).toBe('notControlledByYou');
    expect(issue('createFront',{enemy,provinces:[from,from]}).reason).toBe('badParams');
    expect(issue('createFront',{enemy,provinces:[from]}).ok).toBe(true);
    const foreign=w.units.find(u=>u.owner!==c)!;
    const own=w.units.find(u=>u.owner===c)!;
    expect(issue('assignToFront',{frontId:1,units:[own.id,foreign.id]}).reason).toBe('notYourUnit');
    expect(own.frontId).toBe(-1);
    expect(issue('assignToFront',{frontId:1,units:[own.id]}).ok).toBe(true);
    const auto=applyCommands(w,[{issuer:'frontai',seq:1,type:'frontMove',p:{frontId:1,revision:1,unitId:own.id,target:from}}])[0];
    expect(auto.reason).toBe('staleFrontOrder');
    expect(own.path).toEqual([]);
  });
});
