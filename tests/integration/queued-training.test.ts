import {describe,expect,it} from 'vitest';
import {decode,encode} from '@msgpack/msgpack';
import {createTestEngine} from '../helpers';
import {applyCommands} from '../../src/engine/core/command';
import {tickTraining} from '../../src/engine/systems/training';
import {hashWorld} from '../../src/engine/core/hash';
import {savePayloadChecksum} from '../../src/engine/save/serialize';

async function fixture(){
  const e=await createTestEngine(),w=e.world,c=w.playerCountry,p=w.countries.capital[c];
  let seq=0;
  const issue=(type:string,params:Record<string,unknown>)=>applyCommands(w,[{issuer:'player',seq:++seq,type,p:params}])[0];
  const queue=(priority=5,autoDeploy=false)=>issue('enqueueTraining',{templateId:'light-v1',province:p,priority,autoDeploy});
  const pools=()=>[w.countries.manpowerPool[c],w.countries.infEquipmentStock[c],w.countries.artEquipmentStock[c]];
  return {e,w,c,p,issue,queue,pools};
}
describe('v13 queued training and manual deployment',()=>{
  it('waits for full resources without reservation, then trains and becomes ready for manual deployment',async()=>{
    const {w,c,issue,queue,p,pools}=await fixture();
    w.countries.manpowerPool[c]=0;
    const before=pools(),startUnits=w.units.length;
    expect(queue(7,false).ok).toBe(true);
    const o=w.trainingQueue[0];
    expect(o).toMatchObject({status:'queued',readyTick:-1,priority:7,autoDeploy:false});
    tickTraining(w);
    expect(o.status).toBe('queued');expect(pools()).toEqual(before);
    w.countries.manpowerPool[c]=5000;
    const affordable=pools();
    tickTraining(w);
    expect(o.status).toBe('training');
    expect(o.readyTick).toBe(w.tick+30);
    expect(pools()).toEqual([affordable[0]-5000,affordable[1]-500,affordable[2]-100]);
    w.tick=o.readyTick;tickTraining(w);
    expect(o.status).toBe('ready');expect(w.units).toHaveLength(startUnits);
    expect(issue('deployTraining',{orderId:o.id}).ok).toBe(true);
    expect(w.trainingQueue).toHaveLength(0);
    expect(w.units.find(u=>u.id===o.id)).toMatchObject({owner:c,loc:p,maxManpower:5000});
    expect(issue('deployTraining',{orderId:o.id}).ok).toBe(false);
  });
  it('allocates stock by priority desc then reserved order ID',async()=>{
    const {w,c,queue}=await fixture();
    expect(queue(0,false).ok).toBe(true);
    expect(queue(9,false).ok).toBe(true);
    const [low,high]=w.trainingQueue;
    w.countries.manpowerPool[c]=5000;
    w.countries.infEquipmentStock[c]=500;
    w.countries.artEquipmentStock[c]=100;
    tickTraining(w);
    expect(low.status).toBe('queued');
    expect(high.status).toBe('training');
    expect(w.trainingQueue.map(o=>o.id)).toEqual([low.id,high.id]);
    expect(w.countries.manpowerPool[c]).toBe(0);
  });
  it('refunds only reserved orders and retains ready orders after province loss',async()=>{
    const {w,c,p,issue,queue,pools}=await fixture();
    const baseline=pools();
    expect(queue(5,false).ok).toBe(true);
    const queuedId=w.trainingQueue[0].id;
    expect(issue('cancelTraining',{id:queuedId}).ok).toBe(true);
    expect(pools()).toEqual(baseline);
    expect(queue(5,true).ok).toBe(true);
    const o=w.trainingQueue[0],target=w.prov.controller.findIndex((controller,i)=>controller===c&&i!==p);
    tickTraining(w);
    const booked=pools();
    w.tick=o.readyTick;
    w.prov.controller[p]=w.countries.id.findIndex((_,i)=>i!==c);
    tickTraining(w);
    expect(o.status).toBe('ready');
    expect(issue('deployTraining',{orderId:o.id}).reason).toBe('notControlledByYou');
    expect(issue('setDeploymentProvince',{orderId:o.id,province:target}).ok).toBe(true);
    expect(issue('deployTraining',{orderId:o.id}).ok).toBe(true);
    expect(w.units.find(u=>u.id===o.id)?.loc).toBe(target);
    expect(pools()).toEqual(booked);
    expect(issue('cancelTraining',{id:o.id}).ok).toBe(false);
  });
  it('allows priority changes and cancel of ready orders returns the reservation exactly once',async()=>{
    const {w,c,issue,queue,pools}=await fixture();
    const before=pools();
    expect(queue(5,false).ok).toBe(true);
    const o=w.trainingQueue[0];
    expect(issue('setTrainingPriority',{orderId:o.id,priority:11}).reason).toBe('badParams');
    expect(issue('setTrainingPriority',{orderId:o.id,priority:9}).ok).toBe(true);
    tickTraining(w);expect(o.status).toBe('training');
    w.tick=o.readyTick;tickTraining(w);
    expect(o.status).toBe('ready');
    expect(issue('cancelTraining',{id:o.id}).ok).toBe(true);
    expect(issue('cancelTraining',{id:o.id}).ok).toBe(false);
    expect(pools()).toEqual(before);
    expect(w.countries.manpowerPool[c]).toBeGreaterThanOrEqual(0);
  });
  it('round trips queued / ready state and rejects invalid v13 records',async()=>{
    const {e,w,issue,queue}=await fixture();
    expect(queue(3,false).ok).toBe(true);
    tickTraining(w);expect(w.trainingQueue[0].status).toBe('training');
    w.tick=w.trainingQueue[0].readyTick;tickTraining(w);
    expect(w.trainingQueue[0].status).toBe('ready');
    expect(queue(8,false).ok).toBe(true);
    const bytes=e.serialize(),before=hashWorld(w);
    expect(e.loadFrom(bytes).ok).toBe(true);
    expect(hashWorld(e.world)).toBe(before);
    expect(e.world.trainingQueue.map(o=>o.status)).toEqual(['ready','queued']);
    const corrupt=decode(bytes) as any;
    corrupt.stores.trainingQueue[1].readyTick=17;
    corrupt.payloadChecksum=savePayloadChecksum(corrupt.header,corrupt.stores);
    expect(e.loadFrom(encode(corrupt)).violations).toContain('invalid training order');
    expect(hashWorld(e.world)).toBe(before);
    expect(issue('deployTraining',{orderId:123456}).ok).toBe(false);
  });
  it('accepts v12-shaped legacy orders with original hash',async()=>{
    const {e,w,p,issue}=await fixture();
    expect(issue('startTraining',{templateId:'standard-v1',province:p}).ok).toBe(true);
    const old=decode(e.serialize()) as any;
    delete old.stores.productionLines; delete old.stores.counters.nextProductionLineId; delete old.stores.productionMode; delete old.stores.modelProduction;
    old.header.v=12;
    old.header.integrity=hashWorld(w,false,true,true,true,true,true,true,false);
    old.payloadChecksum=savePayloadChecksum(old.header,old.stores);
    expect(e.loadFrom(encode(old)).ok).toBe(true);
    expect(e.world.trainingQueue[0].status).toBeUndefined();
  });
});
