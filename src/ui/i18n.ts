export const catalogs: Record<Lang, Record<string, string>> = { ja, en };

export function t(
  lang: Lang,
  key: string,
  params?: Record<string, string | number>,
): string {
  const cat = catalogs[lang];
  let s = cat[key] ?? catalogs.ja[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}
